# Human takeover guard (Windows): GetLastInputInfo detects physical mouse/keyboard
# activity between agent actions. A detected user input pauses further control
# until the user explicitly resumes it through desktop_resume_control().
import ctypes
from ctypes import wintypes
import threading

class _LASTINPUTINFO(ctypes.Structure):
    _fields_ = [("cbSize", wintypes.UINT), ("dwTime", wintypes.DWORD)]

_user32 = ctypes.WinDLL("user32", use_last_error=True)
_user32.GetLastInputInfo.argtypes = [ctypes.POINTER(_LASTINPUTINFO)]
_user32.GetLastInputInfo.restype = wintypes.BOOL
_control_lock = threading.RLock()
_control_paused = False
_last_input_tick = 0

def _read_last_input_tick() -> int:
    info = _LASTINPUTINFO()
    info.cbSize = ctypes.sizeof(_LASTINPUTINFO)
    if not _user32.GetLastInputInfo(ctypes.byref(info)):
        raise ctypes.WinError(ctypes.get_last_error())
    return int(info.dwTime)

def _prime_input_baseline() -> None:
    global _last_input_tick
    _last_input_tick = _read_last_input_tick()

def _human_takeover_detected() -> bool:
    global _control_paused, _last_input_tick
    with _control_lock:
        current = _read_last_input_tick()
        if current != _last_input_tick:
            _last_input_tick = current
            _control_paused = True
            return True
        return False

def _control_allowed() -> bool:
    global _control_paused
    with _control_lock:
        if _control_paused:
            return False
        if _human_takeover_detected():
            return False
        return True

def _sync_input_baseline() -> None:
    # Ignore the input just generated by the automation itself.
    global _last_input_tick
    with _control_lock:
        _last_input_tick = _read_last_input_tick()

_prime_input_baseline()

@mcp.tool()
def desktop_control_status() -> str:
    """Reports whether desktop automation is active or paused for human takeover."""
    with _control_lock:
        return "PAUSED: human input detected. Call desktop_resume_control only after the user is ready." if _control_paused else "ACTIVE: no human takeover detected."

@mcp.tool()
def desktop_resume_control() -> str:
    """Resumes desktop automation after a human takeover, when explicitly requested by the user."""
    global _control_paused
    with _control_lock:
        _prime_input_baseline()
        _control_paused = False
    return "Desktop control resumed. Human input baseline reset."
